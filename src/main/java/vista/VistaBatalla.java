    public int getIndiceSeleccionado(int jugador) {
        if (jugador == 0) {
            return listCampoJ1.getSelectedIndex();
        } else {
            return listCampoJ2.getSelectedIndex();
        }
    }

    public void setNombre(int jugador, String nombre) {
        if (jugador == 0) {
            lblNombreJ1.setText(nombre);
        } else {
            lblNombreJ2.setText(nombre);
        }
    }

    public void setLp(int jugador, int lp) {
        if (jugador == 0) {
            lblLpJ1.setText("LP: " + lp);
        } else {
            lblLpJ2.setText("LP: " + lp);
        }
    }

    public void setCampo(int jugador, List<String> items) {
        DefaultListModel<String> modeloLista = new DefaultListModel<>();
        for (String textoMonstruo : items) {
            modeloLista.addElement(textoMonstruo);
        }
        
        if (jugador == 0) {
            listCampoJ1.setModel(modeloLista);
        } else {
            listCampoJ2.setModel(modeloLista);
        }
    }

